package com.synix.uwait_backend.service;

import com.lowagie.text.Font;
import com.lowagie.text.Rectangle;

import com.lowagie.text.*;
import com.lowagie.text.pdf.*;

import java.awt.*;

public class PdfInvoiceFooter extends PdfPageEventHelper {

    Font footerFont = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.GRAY);

    @Override
    public void onEndPage(PdfWriter writer, Document document) {
        PdfPTable footer = new PdfPTable(1);
        footer.setTotalWidth(527);
        footer.setLockedWidth(true);
        footer.getDefaultCell().setBorder(Rectangle.NO_BORDER);

        PdfPCell cell = new PdfPCell(
                new Phrase("Generated by LinkKart • Verified shop • Online invoice only", footerFont)
        );
        cell.setBorder(Rectangle.NO_BORDER);
        cell.setHorizontalAlignment(Element.ALIGN_CENTER);
        footer.addCell(cell);

        footer.writeSelectedRows(0, -1, document.leftMargin(),
                document.bottomMargin() - 5, writer.getDirectContent());
    }
}

