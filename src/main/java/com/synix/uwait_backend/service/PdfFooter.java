package com.synix.uwait_backend.service;

import com.lowagie.text.Font;
import com.lowagie.text.Rectangle;
import com.lowagie.text.*;
import com.lowagie.text.pdf.*;

import java.awt.*;

public class PdfFooter extends PdfPageEventHelper {

    private final Font footerFont =
            new Font(Font.HELVETICA, 9, Font.NORMAL, Color.GRAY);

    @Override
    public void onEndPage(PdfWriter writer, Document document) {

        PdfPTable footer = new PdfPTable(2);
        try {
            footer.setWidths(new float[]{3, 1});
            footer.setTotalWidth(527); // A4 width minus margins
            footer.setLockedWidth(true);
            footer.getDefaultCell().setBorder(Rectangle.NO_BORDER);

            // Left text
            PdfPCell left = new PdfPCell(
                    new Phrase("Generated by AdvueQshopN • One link. One QR. Orders on WhatsApp.", footerFont)
            );
            left.setBorder(Rectangle.NO_BORDER);
            left.setHorizontalAlignment(Element.ALIGN_LEFT);

            // Right page number
            PdfPCell right = new PdfPCell(
                    new Phrase("Page " + writer.getPageNumber(), footerFont)
            );
            right.setBorder(Rectangle.NO_BORDER);
            right.setHorizontalAlignment(Element.ALIGN_RIGHT);

            footer.addCell(left);
            footer.addCell(right);

            footer.writeSelectedRows(
                    0, -1,
                    document.leftMargin(),
                    document.bottomMargin() - 5,
                    writer.getDirectContent()
            );

        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }
}
